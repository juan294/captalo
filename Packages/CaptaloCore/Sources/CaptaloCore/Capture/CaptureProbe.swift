import Foundation

/// Debug probe support (plan phase 2, task 3): whitespace-normalized
/// fixture equality and the clipboard-intact check.
public enum CaptureProbe {
    public enum Result: String, Sendable {
        case pass
        case fail
        case nothingSelected
        case unsupported
    }

    /// Runs of whitespace collapse to one space; ends are trimmed.
    public static func normalize(_ text: String) -> String {
        text.split(whereSeparator: { $0.isWhitespace }).joined(separator: " ")
    }

    public static func result(for outcome: CaptureOutcome, expected: String) -> Result {
        switch outcome {
        case let .text(text, _):
            normalize(text) == normalize(expected) ? .pass : .fail
        case .nothingSelected:
            .nothingSelected
        case .unsupported:
            .unsupported
        case .permissionMissing, .cancelled, .failed:
            .fail
        }
    }

    /// Every original item and type is present and byte-equal, and the only
    /// added types are the two `org.nspasteboard` markers.
    public static func clipboardIntact(before: [PasteboardItemSnapshot], after: [PasteboardItemSnapshot]) -> Bool {
        let markers: Set<String> = [ClipboardTransaction.transientType, ClipboardTransaction.autoGeneratedType]
        guard before.count == after.count else { return false }
        for (old, new) in zip(before, after) {
            let kept = new.entries.filter { !markers.contains($0.type) }
            guard PasteboardItemSnapshot(entries: kept) == old else { return false }
        }
        return true
    }
}
