import AppKit
import Foundation

/// One pasteboard item as materialized data, in type order.
public struct PasteboardItemSnapshot: Equatable, Sendable {
    public var entries: [(type: String, data: Data)]

    public init(entries: [(type: String, data: Data)]) {
        self.entries = entries
    }

    public static func == (lhs: Self, rhs: Self) -> Bool {
        lhs.entries.map(\.type) == rhs.entries.map(\.type) && lhs.entries.map(\.data) == rhs.entries.map(\.data)
    }
}

/// The pasteboard operations the transaction needs. `SystemPasteboard` is
/// the real implementation; tests use it on a uniquely named pasteboard.
@MainActor
public protocol PasteboardAccess: AnyObject {
    var changeCount: Int { get }
    /// Every item and type as data; `nil` entries mark types that failed to materialize.
    func materialize() -> [[(type: String, data: Data?)]]
    func readString() -> String?
    /// Clears the pasteboard and writes `items`. Returns false when the write fails.
    func write(_ items: [PasteboardItemSnapshot]) -> Bool
}

@MainActor
public final class SystemPasteboard: PasteboardAccess {
    public let pasteboard: NSPasteboard

    public init(_ pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
    }

    public var changeCount: Int { pasteboard.changeCount }

    public func materialize() -> [[(type: String, data: Data?)]] {
        (pasteboard.pasteboardItems ?? []).map { item in
            item.types.map { ($0.rawValue, item.data(forType: $0)) }
        }
    }

    public func readString() -> String? {
        pasteboard.string(forType: .string)
    }

    public func write(_ items: [PasteboardItemSnapshot]) -> Bool {
        pasteboard.clearContents()
        guard !items.isEmpty else { return true }
        let objects = items.map { snapshot -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for entry in snapshot.entries {
                item.setData(entry.data, forType: NSPasteboard.PasteboardType(entry.type))
            }
            return item
        }
        return pasteboard.writeObjects(objects)
    }
}

public enum ClipboardResult: Equatable, Sendable {
    case copied(String)
    case cancelled
    case notPreservable
    case ownershipUncertain
    case noCopyResult
    case restoreFailed
    case sourceChanged
    case noText
}

/// A FIFO async lock shared by every transaction in the process.
public actor AsyncSerialLock {
    private var held = false
    private var waiters: [CheckedContinuation<Void, Never>] = []

    public init() {}

    public func acquire() async {
        if !held { held = true; return }
        await withCheckedContinuation { waiters.append($0) }
    }

    public func release() {
        if waiters.isEmpty { held = false } else { waiters.removeFirst().resume() }
    }
}

/// The fenced clipboard transaction (plan phase 2, review R1 and V2-2).
///
/// Before Copy, cancellation always wins. After Copy, the transaction holds a
/// cleanup capability, separate from the input token, that authorizes only
/// attribution and one restore write. Undetectable races are the
/// owner-accepted exception (plan decision 9).
@MainActor
public final class ClipboardTransaction {
    public nonisolated static let transientType = "org.nspasteboard.TransientType"
    public nonisolated static let autoGeneratedType = "org.nspasteboard.AutoGeneratedType"

    public enum Checkpoint: Sendable {
        case duringSnapshot
        case beforeCopy
        case afterRead
    }

    public struct Limits: Sendable {
        public var snapshotBytes = 8 * 1_024 * 1_024
        public var snapshotDuration = Duration.milliseconds(150)
        public var copyWindow = Duration.seconds(1)
        public var pollInterval = Duration.milliseconds(10)

        public init() {}
    }

    private let pasteboard: PasteboardAccess
    private let lock: AsyncSerialLock
    private let limits: Limits
    private let clock: @Sendable () -> ContinuousClock.Instant
    /// Test instrumentation: called at named points to inject foreign writes.
    public var checkpoint: ((Checkpoint) -> Void)?

    public init(
        pasteboard: PasteboardAccess,
        lock: AsyncSerialLock,
        limits: Limits = Limits(),
        clock: @escaping @Sendable () -> ContinuousClock.Instant = { .now }
    ) {
        self.pasteboard = pasteboard
        self.lock = lock
        self.limits = limits
        self.clock = clock
    }

    /// - Parameters:
    ///   - isCurrent: whether the input is still current.
    ///   - sourceUnchanged: frontmost PID and focused element still match the token.
    ///   - copyAction: presses Copy (menu item or synthetic key). Runs at most once.
    public func run(
        isCurrent: @escaping @Sendable () async -> Bool,
        sourceUnchanged: @escaping @Sendable () async -> Bool,
        copyAction: @escaping @Sendable () async -> Void
    ) async -> ClipboardResult {
        await lock.acquire()
        // Step 0: input still current on lock acquisition.
        guard await isCurrent() else {
            await lock.release()
            return .cancelled
        }

        // Step 1: fenced snapshot.
        guard let snapshot = takeSnapshot() else {
            await lock.release()
            return .notPreservable
        }

        // Step 2: recheck right before Copy.
        checkpoint?(.beforeCopy)
        guard await isCurrent() else {
            await lock.release()
            return .cancelled
        }
        guard pasteboard.changeCount == snapshot.changeCount else {
            await lock.release()
            return .ownershipUncertain
        }
        guard await sourceUnchanged() else {
            await lock.release()
            return .sourceChanged
        }

        // From here the cleanup capability runs steps 3-4 even if the input is
        // cancelled or the app quits: an unstructured task ignores the caller's cancellation.
        let lock = self.lock
        let result = await Task { @MainActor in
            await copyAction()
            let result = await self.attributeAndRestore(snapshot)
            await lock.release()
            return result
        }.value
        guard await isCurrent() else { return .cancelled }
        return result
    }

    private struct Snapshot {
        let changeCount: Int
        let items: [PasteboardItemSnapshot]
    }

    private func takeSnapshot() -> Snapshot? {
        let started = clock()
        let c0 = pasteboard.changeCount
        checkpoint?(.duringSnapshot)
        var items: [PasteboardItemSnapshot] = []
        var bytes = 0
        for raw in pasteboard.materialize() {
            var entries: [(type: String, data: Data)] = []
            for entry in raw {
                guard let data = entry.data else { return nil }
                bytes += data.count
                guard bytes <= limits.snapshotBytes else { return nil }
                entries.append((entry.type, data))
            }
            items.append(PasteboardItemSnapshot(entries: entries))
        }
        guard pasteboard.changeCount == c0 else { return nil }
        guard started.duration(to: clock()) <= limits.snapshotDuration else { return nil }
        return Snapshot(changeCount: c0, items: items)
    }

    private func attributeAndRestore(_ snapshot: Snapshot) async -> ClipboardResult {
        // Step 3: wait for the source app's Copy, inside the window.
        let c0 = snapshot.changeCount
        let deadline = clock().advanced(by: limits.copyWindow)
        while pasteboard.changeCount == c0 {
            guard clock() < deadline else { return .noCopyResult }
            try? await Task.sleep(for: limits.pollInterval)
        }
        guard pasteboard.changeCount == c0 + 1 else { return .ownershipUncertain }

        // Step 4: read, final check, restore with markers.
        let text = pasteboard.readString()
        checkpoint?(.afterRead)
        guard pasteboard.changeCount == c0 + 1 else { return .ownershipUncertain }
        let marked = snapshot.items.map { item in
            PasteboardItemSnapshot(entries: item.entries + [(Self.transientType, Data()), (Self.autoGeneratedType, Data())])
        }
        guard pasteboard.write(marked) else {
            PrivacyLog.record(.restoreFailed)
            return .restoreFailed
        }
        guard let text else { return .noText }
        return .copied(text)
    }
}
