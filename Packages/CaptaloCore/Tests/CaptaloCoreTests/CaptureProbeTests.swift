import Foundation
import Testing
@testable import CaptaloCore

@Suite struct CaptureProbeTests {
    @Test func whitespaceIsNormalizedBeforeComparison() {
        let expected = "One  two\n\nthree.\n"
        #expect(CaptureProbe.result(for: .text(" One two three. ", layer: .menuCopy), expected: expected) == .pass)
        #expect(CaptureProbe.result(for: .text("One two three", layer: .menuCopy), expected: expected) == .fail)
        #expect(CaptureProbe.result(for: .nothingSelected, expected: expected) == .nothingSelected)
        #expect(CaptureProbe.result(for: .unsupported(.modifiersHeld), expected: expected) == .unsupported)
        #expect(CaptureProbe.result(for: .failed(.restoreFailed), expected: expected) == .fail)
    }

    @Test func clipboardIntactAllowsOnlyMarkers() {
        let a = PasteboardItemSnapshot(entries: [("public.utf8-plain-text", Data("x".utf8)), ("public.rtf", Data("r".utf8))])
        let marked = PasteboardItemSnapshot(entries: a.entries + [(ClipboardTransaction.transientType, Data()), (ClipboardTransaction.autoGeneratedType, Data())])
        #expect(CaptureProbe.clipboardIntact(before: [a], after: [marked]))
        let changed = PasteboardItemSnapshot(entries: [("public.utf8-plain-text", Data("y".utf8)), ("public.rtf", Data("r".utf8))])
        #expect(!CaptureProbe.clipboardIntact(before: [a], after: [changed]))
        let extra = PasteboardItemSnapshot(entries: a.entries + [("public.html", Data())])
        #expect(!CaptureProbe.clipboardIntact(before: [a], after: [extra]))
        #expect(!CaptureProbe.clipboardIntact(before: [a], after: []))
    }
}
