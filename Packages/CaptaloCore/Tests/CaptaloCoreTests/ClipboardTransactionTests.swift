import AppKit
import Foundation
import Testing
@testable import CaptaloCore

/// Mutable flag readable from `@Sendable` closures.
final class Flag: @unchecked Sendable {
    private let lock = NSLock()
    private var value: Bool
    init(_ value: Bool) { self.value = value }
    func get() -> Bool { lock.lock(); defer { lock.unlock() }; return value }
    func set(_ newValue: Bool) { lock.lock(); value = newValue; lock.unlock() }
}

final class Counter: @unchecked Sendable {
    private let lock = NSLock()
    private var value = 0
    func increment() { lock.lock(); value += 1; lock.unlock() }
    var count: Int { lock.lock(); defer { lock.unlock() }; return value }
}

/// Wraps the real pasteboard to count reads and to fail the restore write.
@MainActor
final class InstrumentedPasteboard: PasteboardAccess {
    let real: SystemPasteboard
    var stringReads = 0
    var materializations = 0
    var failWrites = false
    var unavailableType: String?

    init(_ real: SystemPasteboard) { self.real = real }
    var changeCount: Int { real.changeCount }
    func materialize(byteLimit: Int) -> [[(type: String, data: Data?)]]? {
        materializations += 1
        return real.materialize(byteLimit: byteLimit)?.map { item in item.map { $0.type == unavailableType ? ($0.type, nil) : $0 } }
    }
    func readString() -> String? { stringReads += 1; return real.readString() }
    /// A failing write still clears first, as NSPasteboard requires.
    func write(_ items: [PasteboardItemSnapshot]) -> Bool {
        guard failWrites else { return real.write(items) }
        real.pasteboard.clearContents()
        return false
    }
}

@MainActor
@Suite(.serialized) final class ClipboardTransactionTests {
    let board: NSPasteboard
    let pasteboard: InstrumentedPasteboard
    let customType = NSPasteboard.PasteboardType("com.thecreativetoken.captalo.test-custom")

    init() {
        board = NSPasteboard(name: NSPasteboard.Name("captalo-test-\(UUID().uuidString)"))
        board.clearContents()
        pasteboard = InstrumentedPasteboard(SystemPasteboard(board))
    }

    isolated deinit {
        board.releaseGlobally()
    }

    func fastLimits() -> ClipboardTransaction.Limits {
        var limits = ClipboardTransaction.Limits()
        limits.copyWindow = .milliseconds(200)
        limits.pollInterval = .milliseconds(5)
        return limits
    }

    func makeTransaction(lock: AsyncSerialLock = AsyncSerialLock()) -> ClipboardTransaction {
        ClipboardTransaction(pasteboard: pasteboard, lock: lock, limits: fastLimits())
    }

    /// Two items: plain text plus RTF on the first, a custom type on the second.
    func writeOriginal() -> [PasteboardItemSnapshot] {
        board.clearContents()
        let first = NSPasteboardItem()
        first.setString("original", forType: .string)
        first.setData(Data("{\\rtf1 original}".utf8), forType: .rtf)
        let second = NSPasteboardItem()
        second.setData(Data([0, 1, 2, 3]), forType: customType)
        board.writeObjects([first, second])
        return snapshotNow()
    }

    func snapshotNow() -> [PasteboardItemSnapshot] {
        (pasteboard.materialize(byteLimit: .max) ?? []).map { item in
            PasteboardItemSnapshot(entries: item.map { ($0.type, $0.data ?? Data()) })
        }
    }

    /// The source app's Copy: one pasteboard write.
    func sourceCopy(_ text: String) {
        board.clearContents()
        board.setString(text, forType: .string)
    }

    func foreignWrite() {
        board.clearContents()
        board.setString("foreign", forType: .string)
    }

    func run(
        _ transaction: ClipboardTransaction,
        current: Flag = Flag(true),
        sourceUnchanged: Bool = true,
        sourceCheck: (@MainActor @Sendable () async -> Void)? = nil,
        copy: @escaping @MainActor @Sendable () async -> Void
    ) async -> ClipboardResult {
        await transaction.run(
            isCurrent: { current.get() },
            sourceUnchanged: { await sourceCheck?(); return sourceUnchanged },
            copyAction: { await copy(); return true }
        )
    }

    /// Original items and types are byte-equal; only the two markers were added.
    func expectRestored(_ original: [PasteboardItemSnapshot]) {
        let now = snapshotNow()
        #expect(now.count == original.count)
        for (restored, before) in zip(now, original) {
            let markers = [ClipboardTransaction.transientType, ClipboardTransaction.autoGeneratedType]
            let kept = restored.entries.filter { !markers.contains($0.type) }
            #expect(PasteboardItemSnapshot(entries: kept) == before)
            #expect(Set(restored.entries.map(\.type)).subtracting(before.entries.map(\.type)) == Set(markers))
        }
    }

    @Test func unchangedPasteboardIsNeverRead() async {
        let original = writeOriginal()
        let result = await run(makeTransaction()) {}
        #expect(result == .failed(.noCopyResult))
        #expect(pasteboard.stringReads == 0)
        #expect(snapshotNow() == original)
    }

    @Test func copiedTextReturnedAndOriginalRepresentationsRestored() async {
        let original = writeOriginal()
        let result = await run(makeTransaction()) { self.sourceCopy("selected words") }
        #expect(result == .copied("selected words"))
        expectRestored(original)
    }

    @Test func writeDuringSnapshotAborts() async {
        let original = writeOriginal()
        let transaction = makeTransaction()
        transaction.checkpoint = { if $0 == .duringSnapshot { self.foreignWrite() } }
        let copies = Counter()
        let result = await run(transaction) { copies.increment() }
        #expect(result == .failed(.notPreservable))
        #expect(copies.count == 0)
        #expect(snapshotNow() != original) // the foreign write is kept
    }

    @Test func writeBeforeCopyAborts() async {
        _ = writeOriginal()
        let transaction = makeTransaction()
        transaction.checkpoint = { if $0 == .beforeCopy { self.foreignWrite() } }
        let copies = Counter()
        let result = await run(transaction) { copies.increment() }
        #expect(result == .failed(.ownershipUncertain))
        #expect(copies.count == 0)
        #expect(board.string(forType: .string) == "foreign")
    }

    @Test func secondChangeMeansUncertainNoSpeakNoRestore() async {
        _ = writeOriginal()
        let result = await run(makeTransaction()) {
            self.sourceCopy("selected")
            self.foreignWrite()
        }
        #expect(result == .failed(.ownershipUncertain))
        #expect(pasteboard.stringReads == 0)
        #expect(board.string(forType: .string) == "foreign")
    }

    @Test func writeOrCancelDuringSourceCheckSendsNoCopy() async {
        // The source check (Accessibility) is slow; input currency and the
        // change count are checked after it, immediately before Copy.
        _ = writeOriginal()
        let copies = Counter()
        let written = await run(makeTransaction(), sourceCheck: { self.foreignWrite() }) { copies.increment() }
        #expect(written == .failed(.ownershipUncertain))
        let current = Flag(true)
        let cancelled = await run(makeTransaction(), current: current, sourceCheck: { current.set(false) }) { copies.increment() }
        #expect(cancelled == .cancelled)
        #expect(copies.count == 0)
    }

    @Test func typeThatFailsToMaterializeAborts() async {
        _ = writeOriginal()
        pasteboard.unavailableType = NSPasteboard.PasteboardType.rtf.rawValue
        let copies = Counter()
        #expect(await run(makeTransaction()) { copies.increment() } == .failed(.notPreservable))
        #expect(copies.count == 0)
    }

    @Test func writeBetweenReadAndFinalCheckIsPreserved() async {
        _ = writeOriginal()
        let transaction = makeTransaction()
        transaction.checkpoint = { if $0 == .afterRead { self.foreignWrite() } }
        let result = await run(transaction) { self.sourceCopy("selected") }
        #expect(result == .failed(.ownershipUncertain))
        #expect(board.string(forType: .string) == "foreign")
    }

    @Test func cancelWhileWaitingForLockSendsNoCopy() async {
        _ = writeOriginal()
        let lock = AsyncSerialLock()
        let first = makeTransaction(lock: lock)
        let second = makeTransaction(lock: lock)
        let gate = Gate()
        let secondCurrent = Flag(true)
        let secondCopies = Counter()
        let firstTask = Task { await self.run(first) { await gate.wait(); self.sourceCopy("one") } }
        try? await Task.sleep(for: .milliseconds(20))
        let secondTask = Task { await self.run(second, current: secondCurrent) { secondCopies.increment() } }
        try? await Task.sleep(for: .milliseconds(20))
        secondCurrent.set(false)
        let snapshotsBefore = pasteboard.materializations
        await gate.open()
        #expect(await firstTask.value == .copied("one"))
        #expect(await secondTask.value == .cancelled)
        #expect(secondCopies.count == 0)
        // Step 0: the cancelled waiter takes no snapshot on lock acquisition.
        #expect(pasteboard.materializations == snapshotsBefore)
    }

    @Test func cancelDuringSnapshotSendsNoCopy() async {
        let original = writeOriginal()
        let current = Flag(true)
        let transaction = makeTransaction()
        transaction.checkpoint = { if $0 == .duringSnapshot { current.set(false) } }
        let copies = Counter()
        let result = await run(transaction, current: current) { copies.increment() }
        #expect(result == .cancelled)
        #expect(copies.count == 0)
        #expect(snapshotNow() == original)
    }

    @Test func noChangeWithinWindowRestoresNothing() async {
        let original = writeOriginal()
        let before = board.changeCount
        let result = await run(makeTransaction()) {}
        #expect(result == .failed(.noCopyResult))
        #expect(board.changeCount == before)
        #expect(snapshotNow() == original)
    }

    @Test func overlappingTransactionsAreSerialized() async {
        _ = writeOriginal()
        let lock = AsyncSerialLock()
        let log = EventLog()
        let gate = Gate()
        let first = Task { await self.run(self.makeTransaction(lock: lock)) {
            log.append("copy 1"); await gate.wait(); self.sourceCopy("one"); log.append("copied 1")
        } }
        try? await Task.sleep(for: .milliseconds(20))
        let second = Task { await self.run(self.makeTransaction(lock: lock)) {
            log.append("copy 2"); self.sourceCopy("two")
        } }
        try? await Task.sleep(for: .milliseconds(20))
        #expect(log.events == ["copy 1"])
        await gate.open()
        #expect(await first.value == .copied("one"))
        #expect(await second.value == .copied("two"))
        #expect(log.events == ["copy 1", "copied 1", "copy 2"])
    }

    @Test func cancelAfterCopyStillRunsScopedCleanup() async {
        let original = writeOriginal()
        let current = Flag(true)
        let task = Task { await self.run(self.makeTransaction(), current: current) {
            current.set(false)
            try? await Task.sleep(for: .milliseconds(10))
            self.sourceCopy("selected")
        } }
        task.cancel()
        let result = await task.value
        #expect(result == .cancelled)
        expectRestored(original)
    }

    @Test func cleanupAuthorityGrantsNoOtherEffect() async {
        let original = writeOriginal()
        let current = Flag(true)
        let copies = Counter()
        let before = board.changeCount
        let result = await run(makeTransaction(), current: current) {
            copies.increment()
            self.sourceCopy("selected")
            current.set(false)
        }
        // No text for speech, one Copy, and exactly one restore write after it.
        #expect(result == .cancelled)
        #expect(copies.count == 1)
        #expect(board.changeCount == before + 2)
        #expect(pasteboard.stringReads == 1)
        expectRestored(original)
    }

    @Test func emptyOriginalClipboardIsRestoredEmpty() async {
        board.clearContents()
        let result = await run(makeTransaction()) { self.sourceCopy("selected") }
        #expect(result == .copied("selected"))
        #expect((board.pasteboardItems ?? []).isEmpty)
    }

    @Test func restoreFailureDoesNotSpeak() async {
        _ = writeOriginal()
        pasteboard.failWrites = true
        let result = await run(makeTransaction()) { self.sourceCopy("selected") }
        #expect(result == .failed(.restoreFailed))
        // NSPasteboard clears before writing, so a failed restore leaves it empty.
        #expect((board.pasteboardItems ?? []).isEmpty)
    }

    @Test func unpreservableSnapshotAbortsBeforeCopy() async {
        _ = writeOriginal()
        var limits = fastLimits()
        limits.snapshotBytes = 4
        let copies = Counter()
        let bySize = ClipboardTransaction(pasteboard: pasteboard, lock: AsyncSerialLock(), limits: limits)
        #expect(await run(bySize) { copies.increment() } == .failed(.notPreservable))

        // A slow snapshot (over the 150 ms budget) also aborts before Copy.
        let ticks = Counter()
        let slowClock: @Sendable () -> ContinuousClock.Instant = {
            ticks.increment()
            return ContinuousClock.now.advanced(by: .milliseconds(200 * ticks.count))
        }
        let slow = ClipboardTransaction(pasteboard: pasteboard, lock: AsyncSerialLock(), limits: fastLimits(), clock: slowClock)
        #expect(await run(slow) { copies.increment() } == .failed(.notPreservable))
        #expect(copies.count == 0)
    }

    @Test func sourceChangedBeforeCopyAborts() async {
        _ = writeOriginal()
        let copies = Counter()
        let result = await run(makeTransaction(), sourceUnchanged: false) { copies.increment() }
        #expect(result == .failed(.sourceChanged))
        #expect(copies.count == 0)
    }
}
